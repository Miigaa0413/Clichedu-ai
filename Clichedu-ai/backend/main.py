@app.post("/api/chat")
def chat(request: ChatRequest):

    message = request.message.strip()

    if not message:

        raise HTTPException(
            status_code=400,
            detail="Message хоосон байна."
        )


    # -----------------------------------------------------
    # Conversation
    # -----------------------------------------------------

    conversation_id = request.conversation_id

    if conversation_id is None:

        conversation_id = create_conversation()


    # -----------------------------------------------------
    # Previous messages
    # -----------------------------------------------------

    previous_messages = get_messages(
        conversation_id
    )


    # -----------------------------------------------------
    # Build Gemini context
    # -----------------------------------------------------

    contents = []


    for item in previous_messages:

        role = item["role"]

        if role == "user":

            gemini_role = "user"

        else:

            gemini_role = "model"


        contents.append({

            "role": gemini_role,

            "parts": [
                {
                    "text": item["content"]
                }
            ]

        })


    # Current user message

    contents.append({

        "role": "user",

        "parts": [
            {
                "text": message
            }
        ]

    })


    # -----------------------------------------------------
    # Save user message
    # -----------------------------------------------------

    save_message(
        conversation_id,
        "user",
        message
    )


    # =====================================================
    # GEMINI REQUEST
    # =====================================================

    try:

        response = client.models.generate_content(

            model="gemini-2.5-flash",

            config={

                "system_instruction": SYSTEM_PROMPT,

                "temperature": 0.7,

            },

            contents=contents

        )


        # -------------------------------------------------
        # Get response
        # -------------------------------------------------

        ai_message = response.text


        if not ai_message:

            raise Exception(
                "Gemini хоосон response буцаалаа."
            )


        # -------------------------------------------------
        # Save AI response
        # -------------------------------------------------

        save_message(
            conversation_id,
            "assistant",
            ai_message
        )


        # -------------------------------------------------
        # Return
        # -------------------------------------------------

        return {

            "conversation_id": conversation_id,

            "response": ai_message

        }


    except Exception as e:

        print("================================")
        print("GEMINI ERROR:")
        print(e)
        print("================================")


        raise HTTPException(

            status_code=500,

            detail="Gemini API дээр алдаа гарлаа."

        )


